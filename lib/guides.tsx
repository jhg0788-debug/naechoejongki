import { heightAtZ, type Sex } from "./growth-chart";

export const P3 = -1.881, P97 = 1.881;
export const h = (sex: Sex, age: number, z = 0) => Math.round(heightAtZ(sex, age, z) * 10) / 10;
const gain = (sex: Sex, a: number, b: number) => (h(sex, b) - h(sex, a)) / (b - a);

export interface Guide {
  slug: string; code: string; title: string; description: string; keywords: string[];
  body: () => React.ReactNode;
}

function PercentileTable({ sex, ages }: { sex: Sex; ages: number[] }) {
  return (
    <table>
      <thead><tr><th>나이</th><th>3백분위</th><th>50백분위 (가운데)</th><th>97백분위</th></tr></thead>
      <tbody>
        {ages.map(a => (
          <tr key={a}><td>만 {a}세</td><td>{h(sex, a, P3)}cm</td><td><b>{h(sex, a)}cm</b></td><td>{h(sex, a, P97)}cm</td></tr>
        ))}
      </tbody>
    </table>
  );
}

function GainTable({ rows }: { rows: [string, number, number][] }) {
  return (
    <table>
      <thead><tr><th>나이 구간</th><th>남자아이</th><th>여자아이</th></tr></thead>
      <tbody>
        {rows.map(([label, a, b]) => (
          <tr key={label}><td>{label}</td><td>연 {gain("m", a, b).toFixed(1)}cm</td><td>연 {gain("f", a, b).toFixed(1)}cm</td></tr>
        ))}
      </tbody>
    </table>
  );
}

